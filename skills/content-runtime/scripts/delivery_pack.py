def packaged_draft_paths(run: dict[str, Any], step: str) -> list[str]:
    """Return every final draft explicitly assembled into the current package.

    A matrix package can legitimately reference multiple WeChat or Xiaohongshu
    drafts while the runtime keeps only one ``latest`` pointer per step. The
    package source is the authoritative membership list for delivery.
    """
    expected_prefix = {"write": "pipeline/final/", "xhs": "pipeline/xhs/"}.get(step)
    if not expected_prefix:
        return [str(run.get("steps", {}).get(step, {}).get("latest") or "").strip()]

    source = str(run.get("steps", {}).get("package", {}).get("source") or "")
    paths: list[str] = []
    for token in source.split(";"):
        label, separator, candidate = token.partition(":")
        if not separator or label.strip() != step:
            continue
        rel = candidate.strip()
        if not rel.startswith(expected_prefix) or "\\" in rel or "\x00" in rel:
            continue
        parts = Path(rel).parts
        if any(part in {"", ".", ".."} for part in parts):
            continue
        if rel not in paths:
            paths.append(rel)

    latest = str(run.get("steps", {}).get(step, {}).get("latest") or "").strip()
    if latest and latest not in paths:
        paths.append(latest)
    return paths


def rel_to_project(project: Path, value: str | None) -> str | None:
    if not value:
        return None
    path = Path(value)
    if path.is_absolute():
        try:
            return str(path.relative_to(project))
        except ValueError:
            return str(path)
    return str(path)


def report_file_matches(project: Path, report_file: str, step_rel: str) -> bool:
    if not report_file or not step_rel:
        return False
    report_rel = rel_to_project(project, report_file)
    if report_rel == step_rel:
        return True
    if report_file.endswith(step_rel):
        return True
    try:
        report_abs = Path(report_file).resolve(strict=False)
        step_abs = (project / step_rel).resolve(strict=False)
        return report_abs == step_abs
    except Exception:
        return False


def quality_report_is_fresh(report: dict[str, Any], step_meta: dict[str, Any]) -> bool:
    report_created_at = parse_iso_datetime(report.get("created_at"))
    step_updated_at = parse_iso_datetime(step_meta.get("updated_at"))
    return bool(report_created_at and (not step_updated_at or report_created_at >= step_updated_at))


def quality_report_matches(project: Path, report: dict[str, Any], run: dict[str, Any], step_meta: dict[str, Any]) -> bool:
    step_rel = step_meta.get("latest") or ""
    report_file = str(report.get("file") or "")
    if report_file and not report_file_matches(project, report_file, step_rel):
        return False
    if not quality_report_is_fresh(report, step_meta):
        return False
    if report.get("run_id") and report.get("run_id") == run.get("run_id"):
        return True
    if report.get("slug") and report.get("slug") == run.get("slug"):
        return True
    return bool(report_file and report_file_matches(project, report_file, step_rel))


def matched_quality_reports(project: Path, run: dict[str, Any], limit: int = 5) -> list[Path]:
    root = project / "quality" / "reports"
    if not root.exists():
        return []
    matched: list[Path] = []
    json_reports = sorted(root.glob("*.json"), key=lambda path: path.stat().st_mtime, reverse=True)
    step_metas = [
        meta for step, meta in (run.get("steps") or {}).items()
        if step in FINAL_DRAFT_STEPS and (meta or {}).get("latest")
    ]
    for path in json_reports:
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            continue
        if any(quality_report_matches(project, data, run, meta) for meta in step_metas):
            matched.append(path)
            md = path.with_suffix(".md")
            if md.exists():
                matched.append(md)
        if len(matched) >= limit * 2:
            break
    if matched:
        return matched[: limit * 2]
    if json_reports:
        return []
    # Backward compatibility for older projects that only have markdown reports.
    return newest_files(root, "*.md", limit)


