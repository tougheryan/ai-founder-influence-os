# This is the operator-approved production contract, not a list of every
# auxiliary file generated by the publishing workbench.  A formal handoff has
# exactly one WeChat article, N Xiaohongshu posts, N Moments posts (N >= 1,
# matching the opinion count actually generated in the package) and two
# execution packages for each video platform.  Supporting HTML, WeChat
# share-card copy and Xiaohongshu video variants may still be preserved in the
# sidecar as evidence, but cannot replace any item below.
def publication_contract(opinion_count: int) -> tuple[tuple[str, str, str, str], ...]:
    """Build the delivery contract for a package with ``opinion_count`` opinion posts."""
    count = max(1, int(opinion_count or 0))
    items: list[tuple[str, str, str, str]] = [
        ("wechat", "wechat-article", "draft_fill", "{slug}/wechat-publish.md"),
    ]
    for index in range(1, count + 1):
        items.append(("xiaohongshu", f"xiaohongshu-opinion-{index}", "draft_fill", "{slug}/xiaohongshu-%02d.md" % index))
        items.append(("moments", f"moments-opinion-{index}", "draft_fill", "{slug}/moments-%02d.md" % index))
    for platform in ("shipinhao", "douyin"):
        for index in (1, 2):
            items.append((platform, f"{platform}-video-execution-{index}", "execution_package", "{slug}/%s-short-%02d.md" % (platform, index)))
    return tuple(items)


def opinion_count_from_jobs(jobs: list[Any] | tuple[Any, ...] | None) -> int:
    """Return the opinion count implied by a draft queue's job list."""
    indices: set[int] = set()
    for job in jobs or []:
        if not isinstance(job, dict):
            continue
        item_id = str(job.get("item_id") or "")
        match = re.match(r"^xiaohongshu-opinion-(\d+)$", item_id)
        if match:
            indices.add(int(match.group(1)))
    return len(indices)


