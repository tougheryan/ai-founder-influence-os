TEXT_SCAN_SUFFIXES = {
    ".md", ".txt", ".json", ".jsonl", ".yaml", ".yml", ".csv", ".tsv",
    ".html", ".htm", ".xml", ".js", ".ts", ".tsx", ".jsx", ".css", ".scss",
    ".env", ".log",
}
MAX_TEXT_SCAN_BYTES = 512 * 1024
SENSITIVE_CONTENT_PATTERNS = [
    ("openai-api-key", re.compile(r"\bsk-(?:proj-|live-|test-)?[A-Za-z0-9_-]{20,}\b")),
    ("anthropic-api-key", re.compile(r"\bsk-ant-[A-Za-z0-9_-]{20,}\b")),
    ("google-api-key", re.compile(r"\bAIza[0-9A-Za-z_-]{20,}\b")),
    ("deepseek-api-key", re.compile(r"\bsk-[A-Za-z0-9]{32,}\b")),
    ("jwt-token", re.compile(r"\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\b")),
    ("private-key", re.compile(r"-----BEGIN (?:RSA |EC |OPENSSH |)?PRIVATE KEY-----")),
    ("access-token-assignment", re.compile(r"(?i)\b(?:api[_-]?key|secret|access[_-]?token|refresh[_-]?token|bearer)\b\s*[:=]\s*['\"]?[A-Za-z0-9._/\-+]{16,}")),
]
LOCAL_ABSOLUTE_PATH_RE = re.compile(r"(?<![\w:])/(?:Users|private|tmp|var/folders|home|Volumes)/[^\s`\"'，。；;]+")
DELIVERY_CONTENT_PATTERNS = [
    *SENSITIVE_CONTENT_PATTERNS,
    ("local-absolute-path", LOCAL_ABSOLUTE_PATH_RE),
]


def safe_name(value: str) -> str:
    safe = re.sub(r"[^0-9A-Za-z._\-\u4e00-\u9fff]+", "-", str(value or "").strip())
    return safe.strip(".-") or "delivery"


def is_sensitive_path(path: Path | str) -> bool:
    parts = [part.lower() for part in Path(str(path)).parts if part not in {"", "/", "\\"}]
    return any(
        part in SENSITIVE_PATH_COMPONENTS
        or part.endswith(".lock")
        or part.endswith(".cookie")
        for part in parts
    )


def should_scan_text(path: Path) -> bool:
    if path.suffix.lower() in TEXT_SCAN_SUFFIXES:
        return True
    return path.name.lower() in {".env", ".npmrc"}


def sensitive_content_hits(path: Path) -> list[str]:
    return content_hits(path, SENSITIVE_CONTENT_PATTERNS)


def delivery_content_hits(path: Path) -> list[str]:
    return content_hits(path, DELIVERY_CONTENT_PATTERNS)


def content_hits(path: Path, patterns: list[tuple[str, re.Pattern[str]]]) -> list[str]:
    if not path.exists() or not path.is_file() or not should_scan_text(path):
        return []
    try:
        if path.stat().st_size > MAX_TEXT_SCAN_BYTES:
            return []
        text = path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return []
    hits = []
    for label, pattern in patterns:
        if pattern.search(text):
            hits.append(label)
    return hits


def is_sensitive_file(path: Path | str, relative_path: Path | str | None = None) -> bool:
    source = Path(path)
    return is_sensitive_path(relative_path if relative_path is not None else source) or bool(sensitive_content_hits(source))


def redact_local_paths_for_delivery(text: str, project: Path | None = None) -> str:
    project_root = project.resolve(strict=False) if project else None

    def replace(match: re.Match[str]) -> str:
        raw = match.group(0)
        core = raw.rstrip(").,]}>")
        suffix = raw[len(core):]
        try:
            candidate = Path(core).resolve(strict=False)
            if project_root:
                relation = candidate.relative_to(project_root)
                return str(relation) + suffix
        except ValueError:
            pass
        except OSError:
            pass
        return "[local path redacted]" + suffix

    return LOCAL_ABSOLUTE_PATH_RE.sub(replace, text)


def copy_delivery_file(source: Path, target: Path, project: Path | None = None) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    if should_scan_text(source):
        text = source.read_text(encoding="utf-8", errors="ignore")
        target.write_text(redact_local_paths_for_delivery(text, project), encoding="utf-8")
        return
    shutil.copy2(source, target)


def _project_regular_file(project: Path, rel_path: str) -> Path | None:
    """Resolve one ordinary project file without allowing traversal or symlinks."""
    project_root = Path(project).expanduser().resolve(strict=False)
    relative = Path(rel_path)
    if (
        relative.is_absolute()
        or "\\" in rel_path
        or "\x00" in rel_path
        or any(part in {"", ".", ".."} for part in relative.parts)
    ):
        raise RuntimeError(f"delivery artifact path must be a safe project-relative path: {rel_path}")
    current = project_root
    for part in relative.parts:
        current = current / part
        if current.is_symlink():
            raise RuntimeError(f"delivery artifact path must not use a symlink: {rel_path}")
    source = (project_root / relative).resolve(strict=False)
    try:
        source.relative_to(project_root)
    except ValueError as exc:
        raise RuntimeError(f"delivery artifact path must be project-relative: {rel_path}") from exc
    if not source.exists():
        return None
    if not source.is_file():
        raise RuntimeError(f"delivery artifact must be a project file: {rel_path}")
    return source


def copy_if_exists(project: Path, rel_path: str | None, dest_dir: Path) -> str | None:
    if not rel_path:
        return None
    source = _project_regular_file(project, rel_path)
    if source is None:
        return None
    if is_sensitive_file(source, Path(rel_path)):
        return None
    dest_dir.mkdir(parents=True, exist_ok=True)
    target = dest_dir / source.name
    copy_delivery_file(source, target, project)
    return str(target)


def _is_current_publish_asset_path(relative: Path, slug: str) -> bool:
    """Allow only this slug's generated files plus its report and sidecar."""
    generated_root = PUBLISH_ASSETS_ROOT / slug
    report_path = PUBLISH_ASSETS_ROOT / f"{slug}-publish-assets.md"
    sidecar_path = PUBLISH_ASSETS_ROOT / f"{slug}-platform-deliverables.json"
    return relative == report_path or relative == sidecar_path or relative.is_relative_to(generated_root)


def is_allowed_publication_asset_path(relative: Path | str, slug: str) -> bool:
    """Allow the fixed publish contract plus known supporting evidence files.

    The sidecar is generated outside the Python runtime and is therefore input
    we have to distrust.  The supporting forms below are intentionally narrow:
    they are useful for internal proof and manual publishing, but never expand
    the fixed 1+3+3+2+2 customer-facing contract.
    """
    path = Path(relative)
    safe_slug = safe_name(slug)
    generated_root = PUBLISH_ASSETS_ROOT / safe_slug
    report_path = PUBLISH_ASSETS_ROOT / f"{safe_slug}-publish-assets.md"
    sidecar_path = PUBLISH_ASSETS_ROOT / f"{safe_slug}-platform-deliverables.json"
    if path in {report_path, sidecar_path}:
        return True
    if str(path) in required_platform_publish_paths(safe_slug):
        return True
    if not path.is_relative_to(generated_root):
        return False
    local = path.relative_to(generated_root)
    if local == Path("wechat-source.md"):
        return True
    if local.as_posix() in {"xiaohongshu-01.txt", "shipinhao-native-01.md"}:
        return True
    if re.fullmatch(r"wechat-share-0[1-3]\.md", local.as_posix()):
        return True
    if re.fullmatch(r"xiaohongshu-video-short-0[1-2]\.md", local.as_posix()):
        return True
    # DBS-generated HTML evidence remains useful for operator review. It is not
    # a new content slot and must stay in its dedicated directory.
    return (
        len(local.parts) == 2
        and local.parts[0] == "wechat-html"
        and local.suffix.lower() in {".html", ".md"}
    )


def copy_platform_publish_assets(project: Path, slug: str | None, dest_dir: Path) -> dict[str, Any]:
    """Copy direct-publish files named by the current slug's immutable sidecar.

    The publish-assets JSON is treated as untrusted input. It can name only files
    belonging to the current slug and every accepted path is rechecked as an
    ordinary, non-sensitive project file before copying.
    """
    result: dict[str, Any] = {
        "source": None,
        "copied_to": None,
        "files": [],
        "declared_count": 0,
        "missing_count": 0,
        "rejected_count": 0,
        "skipped_sensitive_count": 0,
        "errors": [],
        "privacy_status": "ok",
    }
    if not slug:
        return result

    project_root = Path(project).expanduser().resolve(strict=False)
    safe_slug = safe_name(slug)
    sidecar_relative = PUBLISH_ASSETS_ROOT / f"{safe_slug}-platform-deliverables.json"
    sidecar_candidate = project_root / sidecar_relative
    # Keep an invalid sidecar visible to the delivery audit.  Otherwise a
    # symlinked or otherwise unsafe sidecar would be silently omitted and the
    # customer ZIP could look complete while losing all platform publish forms.
    sidecar_present = sidecar_candidate.exists() or sidecar_candidate.is_symlink()
    try:
        sidecar = _project_regular_file(project_root, str(sidecar_relative))
    except RuntimeError:
        if sidecar_present:
            result["source"] = str(sidecar_relative)
        result["rejected_count"] = 1
        result["errors"] = ["platform-deliverables-sidecar-invalid"]
        return result
    if sidecar is None:
        return result

    result["source"] = str(sidecar_relative)
    if is_sensitive_file(sidecar, sidecar_relative):
        result["skipped_sensitive_count"] = 1
        result["privacy_status"] = "skipped_sensitive"
        return result

    copied_sidecar = copy_if_exists(project_root, str(sidecar_relative), dest_dir)
    if not copied_sidecar:
        result["missing_count"] = 1
        return result
    result["copied_to"] = copied_sidecar

    try:
        payload = json.loads(sidecar.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError):
        result["errors"] = ["platform-deliverables-sidecar-malformed"]
        return result
    archive = payload.get("archive") if isinstance(payload, dict) else None
    generated_paths = archive.get("generatedPaths") if isinstance(archive, dict) else None
    if not isinstance(generated_paths, list):
        result["errors"] = ["platform-deliverables-generated-paths-missing"]
        return result

    seen: set[str] = set()
    files: list[str] = []
    for raw_path in generated_paths:
        if not isinstance(raw_path, str) or not raw_path.strip():
            result["rejected_count"] += 1
            continue
        relative = Path(raw_path)
        if raw_path in seen:
            continue
        seen.add(raw_path)
        if not _is_current_publish_asset_path(relative, safe_slug) or not is_allowed_publication_asset_path(relative, safe_slug):
            result["rejected_count"] += 1
            continue
        if relative == sidecar_relative:
            continue
        result["declared_count"] += 1
        try:
            source = _project_regular_file(project_root, raw_path)
        except RuntimeError:
            result["rejected_count"] += 1
            continue
        if source is None:
            result["missing_count"] += 1
            continue
        if is_sensitive_file(source, relative):
            result["skipped_sensitive_count"] += 1
            result["privacy_status"] = "skipped_sensitive"
            continue
        target_dir = dest_dir / relative.relative_to(PUBLISH_ASSETS_ROOT).parent
        copied = copy_if_exists(project_root, raw_path, target_dir)
        if not copied:
            result["missing_count"] += 1
            continue
        files.append(copied)

    result["files"] = files
    return result


