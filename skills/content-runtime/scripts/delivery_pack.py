def privacy_checklist(result: dict[str, Any]) -> str:
    flagged = result["privacy_scan"].get("flagged") or []
    content_flagged = result["privacy_scan"].get("content_flagged") or []
    lines = [
        f"# 隐私与敏感文件检查 · {result['run_id']}",
        "",
        f"- 检查状态：{result['privacy_scan']['status']}",
        f"- 文件数量：{result['privacy_scan']['file_count']}",
        "",
        "## 已检查规则",
        "",
    ]
    for rule in result["privacy_scan"]["rules"]:
        lines.append(f"- `{rule}`")
    if result["privacy_scan"].get("content_rules"):
        lines.extend(["", "## 已检查内容规则", ""])
        for rule in result["privacy_scan"]["content_rules"]:
            lines.append(f"- `{rule}`")
    lines.extend(["", "## 命中文件", ""])
    if flagged:
        lines.extend(f"- `{item}`" for item in flagged)
    else:
        lines.append("- 未发现登录态、浏览器诊断包、trace、页面 HTML、session 状态等敏感文件。")
    lines.extend(["", "## 内容敏感命中", ""])
    if content_flagged:
        for item in content_flagged:
            lines.append(f"- `{item.get('path')}`：{', '.join(item.get('hits') or [])}")
    else:
        lines.append("- 未发现 API key、访问令牌、私钥等高置信敏感内容。")
    lines.extend([
        "",
        "## 人工确认",
        "",
        "- [ ] 未包含客户账号登录态、cookie、浏览器 profile。",
        "- [ ] 未包含未授权截图、私信、用户个人信息。",
        "- [ ] 第三方内容只保留公开元数据、链接、摘要和自己的分析。",
    ])
    return "\n".join(lines)


def write_customer_delivery_files(result: dict[str, Any], dest: Path, project: Path) -> None:
    (dest / "README.md").write_text(customer_readme(result), encoding="utf-8")
    (dest / "客户交付说明.md").write_text(customer_readme(result), encoding="utf-8")
    (dest / "客户成果报告.md").write_text(delivery_summary(result), encoding="utf-8")
    (dest / "修改意见回填.md").write_text(feedback_template(result), encoding="utf-8")
    (dest / "隐私检查清单.md").write_text(privacy_checklist(result), encoding="utf-8")
    marker = dest / INTERNAL_REVIEW_MARKER
    if is_formal_delivery(result):
        marker.unlink(missing_ok=True)
    else:
        marker.write_text(internal_review_notice(result), encoding="utf-8")
    (dest / "manifest.json").write_text(
        json.dumps(customer_manifest(result, dest, project), ensure_ascii=False, indent=2),
        encoding="utf-8",
    )


def stabilize_customer_delivery_files(result: dict[str, Any], dest: Path, project: Path, max_attempts: int = 4) -> None:
    """Write customer files until the embedded privacy scan matches the package."""
    for _ in range(max_attempts):
        write_customer_delivery_files(result, dest, project)
        current_scan = privacy_scan(dest)
        if current_scan == result.get("privacy_scan"):
            return
        result["privacy_scan"] = current_scan
    write_customer_delivery_files(result, dest, project)
    final_scan = privacy_scan(dest)
    if final_scan != result.get("privacy_scan"):
        raise RuntimeError("交付包隐私扫描无法收敛，请检查客户文档、manifest 或隐私扫描规则。")


def build_delivery_pack(project: str | Path, run_id: str | None = None, slug: str | None = None) -> dict[str, Any]:
    rt = ContentRuntime(project)
    rt.init()
    run = rt.run_state(run_id=run_id, slug=slug)
    selected_run_id = run.get("run_id")
    selected_slug = run.get("slug")
    created_at = datetime.now().isoformat()
    stamp = datetime.now().strftime("%Y-%m-%d-%H%M%S")
    gate = delivery_gate(rt.project, run)
    native_contract = (gate.get("publication_prerequisites") or {}).get("contract")
    formal_delivery = bool(gate.get("can_deliver"))
    delivery_scope = FORMAL_DELIVERY_SCOPE if formal_delivery else INTERNAL_REVIEW_SCOPE
    suffix = "" if formal_delivery else "-internal-review"
    dest = rt.project / "deliveries" / f"{stamp}-{safe_name(selected_run_id)}{suffix}"
    artifacts_dir = dest / "artifacts"
    reports_dir = dest / "reports"
    artifacts: list[dict[str, Any]] = []

    delivery_steps = ([(step, label) for step, label in DELIVERY_STEPS if run.get("steps", {}).get(step, {}).get("latest")]
                      if native_delivery.is_native_run(run) else DELIVERY_STEPS)
    for step, label in delivery_steps:
        rel_paths = packaged_draft_paths(run, step) if step in FINAL_DRAFT_STEPS else [
            run.get("steps", {}).get(step, {}).get("latest")
        ]
        total = len([item for item in rel_paths if item])
        for position, rel in enumerate(rel_paths, start=1):
            copied = copy_if_exists(rt.project, rel, artifacts_dir / step)
            member_label = f"{label} {position}/{total}" if total > 1 else label
            artifacts.append({
                "step": step,
                "label": member_label,
                "source": rel,
                "copied_to": copied,
                "privacy_status": "skipped_sensitive" if rel and not copied and is_sensitive_path(rel) else "ok",
            })

    for step, label in OPTIONAL_DELIVERY_STEPS:
        rel = run.get("steps", {}).get(step, {}).get("latest")
        if not rel:
            continue
        copied = copy_if_exists(rt.project, rel, artifacts_dir / step)
        artifacts.append({
            "step": step,
            "label": label,
            "source": rel,
            "copied_to": copied,
            "privacy_status": "skipped_sensitive" if rel and not copied and is_sensitive_path(rel) else "ok",
        })

    visual_assets = copy_visual_assets(rt.project, selected_slug, artifacts_dir / "visual-assets")
    artifacts.append({
        "step": "visual-assets",
        "label": "视觉生成资产",
        "source": f"pipeline/visual/{safe_name(selected_slug)}/*" if selected_slug else None,
        "copied_to": str(artifacts_dir / "visual-assets") if visual_assets else None,
        "files": visual_assets,
        "privacy_status": "ok",
    })

    publish_assets = copy_platform_publish_assets(
        rt.project,
        selected_slug,
        artifacts_dir / "publish-assets",
    )
    if (
        publish_assets.get("source")
        or publish_assets.get("errors")
        or publish_assets.get("rejected_count")
        or publish_assets.get("missing_count")
        or publish_assets.get("skipped_sensitive_count")
    ):
        artifacts.append({
            "step": "publish-assets",
            "label": "本期平台发布成稿" if native_delivery.is_native_run(run) else "五平台发布成稿",
            **publish_assets,
        })

    draft_queue = copy_publication_draft_queue(
        rt.project,
        selected_slug,
        artifacts_dir / "publication-draft-queue",
    )
    artifacts.append({
        "step": "publication-draft-queue",
        "label": "本期平台草稿队列" if native_delivery.is_native_run(run) else "五平台草稿队列",
        **draft_queue,
    })

    benchmark_reports = copy_report_files(matched_benchmark_reports(rt.project, run), reports_dir / "benchmark", rt.project)
    quality_reports = copy_report_files(matched_quality_reports(rt.project, run, 5), reports_dir / "quality", rt.project)
    system_audit_reports = copy_report_files(matched_system_audit_reports(rt.project, run, 3), reports_dir / "system-audit", rt.project)

    pipeline_status = PipelineDirector(rt.project, slug=selected_slug).status()
    platform_labels = []
    for platform in run.get("target_platforms") or pipeline_status.get("target_platforms") or []:
        label = PLATFORM_LABELS.get(platform, platform)
        if label not in platform_labels:
            platform_labels.append(label)

    result = {
        "status": "ready_for_delivery" if formal_delivery else "internal_review_only",
        "delivery_scope": delivery_scope,
        "formal_delivery": formal_delivery,
        "project": str(rt.project),
        "run_id": selected_run_id,
        "slug": selected_slug,
        "topic": run.get("topic", ""),
        "platforms": run.get("target_platforms", []),
        "platform_labels": platform_labels,
        "created_at": created_at,
        "delivery_dir": str(dest),
        "artifacts": artifacts,
        "reports": benchmark_reports + quality_reports + system_audit_reports,
        "benchmark_reports": benchmark_reports,
        "quality_reports": quality_reports,
        "system_audit_reports": system_audit_reports,
        "delivery_gate": gate,
        "pipeline": pipeline_status,
        "privacy_scan": {"status": "pending", "file_count": 0, "flagged": [], "rules": SENSITIVE_PATTERNS},
        **({"selected_platform_contract": native_contract} if native_contract else {}),
    }
    dest.mkdir(parents=True, exist_ok=True)
    stabilize_customer_delivery_files(result, dest, rt.project)
    if formal_delivery:
        if native_contract:
            errors = native_delivery.inspect_bundle(result, dest)
            current = native_delivery.prerequisites(rt.project, run)
            if current["errors"] or (current.get("contract") or {}).get("sha256") != native_contract["sha256"]:
                errors.append("打包期间来源或确认记录发生变化，请重新审查。")
            if errors or result["privacy_scan"].get("status") != "pass":
                raise RuntimeError("交付文件核验失败，未生成 ZIP：" + "；".join(errors))
        result["zip_path"] = shutil.make_archive(str(dest), "zip", root_dir=dest)
        if native_contract:
            errors = native_delivery.inspect_bundle(result, dest, result["zip_path"])
            if errors:
                Path(result["zip_path"]).unlink()
                raise RuntimeError("ZIP 核验失败：" + "；".join(errors))
    else:
        # A blocked/review run can retain a local evidence directory, but a ZIP
        # would look like a customer handoff when shared outside the workbench.
        # Keep the result explicitly local and make the absence of a ZIP part of
        # the API contract instead of relying on UI wording alone.
        result["zip_path"] = None
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description="Echo Founder commercial delivery pack generator")
    parser.add_argument("--project", required=True)
    parser.add_argument("--run-id", default=None)
    parser.add_argument("--slug", default=None)
    args = parser.parse_args()
    try:
        print(json.dumps(build_delivery_pack(args.project, args.run_id, args.slug), ensure_ascii=False, indent=2))
        return 0
    except Exception as exc:
        print(json.dumps({"error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
