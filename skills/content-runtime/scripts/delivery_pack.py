def render_recommended_actions(actions: list[dict[str, Any]], limit: int = 5) -> list[str]:
    lines: list[str] = []
    for index, item in enumerate(actions[:limit], 1):
        title = item.get("title") or item.get("id") or "建议动作"
        owner = item.get("owner") or "未指定"
        severity = item.get("severity") or "review"
        issue_count = item.get("issue_count") or len(item.get("issue_codes") or []) or 1
        lines.append(f"{index}. {title}（{severity}，负责人：{owner}，问题数：{issue_count}）")
        summary = item.get("summary")
        if summary:
            lines.append(f"   - 依据：{summary}")
        command = item.get("command")
        if command:
            lines.append(f"   - 执行：`{command}`")
    if not lines:
        lines.append("- 暂无系统建议动作。")
    return lines


