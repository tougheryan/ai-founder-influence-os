def delivery_summary(result: dict[str, Any]) -> str:
    provided = [item for item in result["artifacts"] if item.get("copied_to")]
    missing = [item for item in result["artifacts"] if not item.get("copied_to")]
    pipeline = result.get("pipeline", {})
    warnings = pipeline.get("warnings") or []
    gate = result.get("delivery_gate") or {}
    recommended_actions = gate.get("recommended_actions") or []
    formal = is_formal_delivery(result)
    lines = [
        f"# {'客户成果报告' if formal else '内部复核成果清单（禁止直接交付）'} · {result['run_id']}",
        "",
        *([] if formal else [
            "**当前资料只用于内部复核和修复，不得作为正式客户交付或发布附件。**",
            "",
        ]),
        f"- 主题：{result.get('topic') or '未填写'}",
        f"- 目标阵地：{', '.join(result['platform_labels']) or '未指定'}",
        f"- 交付时间：{result['created_at']}",
        f"- 交付资格：{gate.get('label') or '未审查'}",
        "",
        "## 1. 本次交付内容",
        "",
        f"本次交付围绕「{result.get('topic') or result['slug']}」整理内容生产链路，已提供 {len(provided)} 类产物。",
        "",
        "| 模块 | 状态 | 文件 |",
        "|---|---|---|",
    ]
    for item in result["artifacts"]:
        status = "已交付" if item.get("copied_to") else "未提供"
        lines.append(f"| {item['label']} | {status} | {item.get('source') or ''} |")
    lines.extend([
        "",
        "## 2. 质量与风控",
        "",
        f"- 交付资格：{gate.get('label') or '未审查'}",
        f"- 资格说明：{gate.get('message') or '尚未读取到交付审查结论。'}",
        f"- 质量报告：{len(result.get('quality_reports', []))} 份",
        f"- 系统交付审查报告：{len(result.get('system_audit_reports', []))} 份",
        f"- 爆款对标报告：{len(result.get('benchmark_reports', []))} 份",
        f"- 隐私检查：{result['privacy_scan']['status']}",
    ])
    if warnings:
        lines.append(f"- 流水线警告：{len(warnings)} 条，建议交付前人工复核。")
    else:
        lines.append("- 流水线警告：暂无。")
    lines.extend([
        "",
        "## 3. 建议动作",
        "",
        *render_recommended_actions(recommended_actions),
        "",
        "## 4. 客户需要确认",
        "",
        "- 内容方向是否符合业务定位和目标用户。",
        "- 案例、硬数字、客户名称、平台截图是否允许公开使用。",
        "- 各目标平台的长文、图文或短视频执行稿是否按本次交付范围准备齐全。",
        "- 如需修改，请在 `修改意见回填.md` 中填写。",
        "",
        "## 5. 发布后回填",
        "",
        "- 发布时间、阅读/播放、点赞、收藏、评论、转发。",
        "- 咨询/私信线索数量。",
        "- 高价值评论和用户反对意见。",
        "- 发布后数据会进入 review/archive/twin，沉淀为下一条内容的素材。",
    ])
    if missing:
        lines.extend(["", "## 6. 缺失项", ""])
        for item in missing:
            lines.append(f"- {item['label']}：{item.get('source') or '本 run 尚未生成'}")
    lines.append("")
    return "\n".join(lines)


