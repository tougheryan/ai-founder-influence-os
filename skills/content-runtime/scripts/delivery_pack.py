def delivery_gate_run_arg(run: dict[str, Any]) -> str:
    run_id = str(run.get("run_id") or "").strip()
    slug = str(run.get("slug") or "").strip()
    if run_id:
        return f"RUN_ID={run_id}"
    if slug:
        return f"SLUG={slug}"
    return ""


def gate_action(
    *,
    action_id: str,
    title: str,
    owner: str,
    severity: str,
    issue_codes: list[str],
    artifacts: list[str] | None = None,
    messages: list[str] | None = None,
    command: str,
) -> dict[str, Any]:
    clean_messages = [item for item in (messages or []) if item]
    return {
        "id": action_id,
        "title": title,
        "owner": owner,
        "severity": severity,
        "issue_codes": issue_codes,
        "issue_count": max(len(clean_messages), 1),
        "artifacts": [item for item in (artifacts or []) if item][:5],
        "messages": clean_messages[:5],
        "command": command.strip(),
        "summary": "；".join(clean_messages[:3]) or title,
    }


def delivery_audit_command(run: dict[str, Any]) -> str:
    run_arg = delivery_gate_run_arg(run)
    return f"make delivery-audit {run_arg} AUTO_PACK=1".strip()


