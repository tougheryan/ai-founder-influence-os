def _label_demo_concept_visuals(body: str) -> str:
    """Mark demo page visuals as concepts so they cannot be mistaken for evidence."""
    rendered: list[str] = []
    for line in body.splitlines():
        if line.lstrip().startswith("| P"):
            cells = line.split("|")
            if len(cells) >= 8:
                visual = cells[4].strip()
                if visual and not any(
                    marker in visual
                    for marker in ("materials/", "pipeline/", "来源：", "来源:", "非事实证据")
                ):
                    cells[4] = f" 概念图解（非事实证据）：{visual} "
                    line = "|".join(cells)
        rendered.append(line)
    return "\n".join(rendered)


